const endpoint = process.argv[2] || 'http://127.0.0.1:9224';
const targetUrl = process.argv[3] || 'http://127.0.0.1:8765/games/snake.html';
const version = await fetch(`${endpoint}/json/version`).then(response => response.json());
const socket = new WebSocket(version.webSocketDebuggerUrl);
let id = 0;
const pending = new Map();
socket.onmessage = event => {
    const message = JSON.parse(event.data);
    if (!message.id || !pending.has(message.id)) return;
    const request = pending.get(message.id);
    pending.delete(message.id);
    message.error ? request.reject(message.error) : request.resolve(message.result);
};
await new Promise((resolve, reject) => { socket.onopen = resolve; socket.onerror = reject; });
const send = (method, params = {}, sessionId) => new Promise((resolve, reject) => {
    const messageId = ++id;
    pending.set(messageId, { resolve, reject });
    socket.send(JSON.stringify({ id: messageId, method, params, ...(sessionId ? { sessionId } : {}) }));
});
const { targetId } = await send('Target.createTarget', { url: 'about:blank' });
